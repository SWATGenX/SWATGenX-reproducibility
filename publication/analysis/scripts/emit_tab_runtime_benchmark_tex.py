#!/usr/bin/env python3
"""Emit LaTeX tabular for tab-runtime-benchmark.csv."""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_CSV = REPO_ROOT / "publication/tables/tab-runtime-benchmark.csv"
DEFAULT_OUT = REPO_ROOT / "publication/tables/generated/tab-runtime-benchmark.tex"


def emit(csv_path: Path, out_path: Path) -> None:
    with csv_path.open(newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r.get("status", "").startswith("frozen")]
    if not rows:
        raise SystemExit("ERROR: no frozen runtime benchmark rows")

    lines = [
        "% Generated by emit_tab_runtime_benchmark_tex.py",
        f"% Source: {csv_path.as_posix()}",
        r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llrrrr@{}}",
        r"\toprule",
        r"Size class & Model & HRUs & Wall (s) & s/day & Peak RSS (KB) \\",
        r"\midrule",
    ]
    for r in rows:
        lines.append(
            f"{r['tier']} & \\texttt{{{r['model_id']}}} & {r['hrus']} & "
            f"{r['wall_s']} & {r['sec_per_day']} & {r['peak_rss_kb']} \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{tabular*}", ""])
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} ({len(rows)} rows)")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = p.parse_args()
    emit(args.csv, args.out)


if __name__ == "__main__":
    main()
