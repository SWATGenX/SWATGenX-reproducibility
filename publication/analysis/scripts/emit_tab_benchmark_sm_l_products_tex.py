#!/usr/bin/env python3
"""Emit merged Objective 3 table: structure + on-disk size + generation time for S/M/L."""
from __future__ import annotations

import csv
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
COMPLEXITY = REPO / "publication/tables/tab-model-complexity.csv"
PRODUCT = REPO / "publication/tables/tab-product-metrics.csv"
RUNTIME = REPO / "publication/tables/tab-runtime.csv"
OUT = REPO / "publication/tables/generated/tab-benchmark-sm-l-products.tex"

TIER_ORDER = {"S": 0, "M": 1, "L": 2}


def _load_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main() -> None:
    complexity = {r["catalog_model_id"]: r for r in _load_csv(COMPLEXITY)}
    product = {r["catalog_model_id"]: r for r in _load_csv(PRODUCT)}
    runtime = {r["catalog_model_id"]: r for r in _load_csv(RUNTIME)}

    ids = sorted(complexity.keys(), key=lambda k: TIER_ORDER.get(complexity[k]["tier"], 9))
    lines = [
        r"% Generated by publication/analysis/scripts/emit_tab_benchmark_sm_l_products_tex.py",
        r"\begin{tabular}{@{}lllrrrrrr@{}}",
        r"\toprule",
        r"Size class & Model ID & Basin & Area (km$^2$) & HRUs & Channels & Subbasins & On-disk (MB) & Assembly (min) \\",
        r"\midrule",
    ]
    for cid in ids:
        c = complexity[cid]
        p = product.get(cid, {})
        r = runtime.get(cid, {})
        area = f"{float(c['area_km2']):.1f}"
        size = p.get("tree_size_mb", "---")
        wall = r.get("fresh_rerun_wall_min", "---")
        if wall and wall != "---":
            wall = f"{float(wall):.1f}"
        label = c.get("label") or cid
        lines.append(
            f"{c['tier']} & \\texttt{{{cid}}} & {label} & {area} & {c['n_hrus']} & {c['n_channels']} "
            f"& {c['n_subbasins']} & {size} & {wall} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({len(ids)} rows)")


if __name__ == "__main__":
    main()
